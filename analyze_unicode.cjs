// Detailed unicode decomposition analysis
const words = [
    'महाराष्ट्र',     // म + ह + ा + र + ा + ष + ् + ट + ् + र
    'विद्यार्थी',     // व + ि + द + ् + य + ा + र + ् + थ + ी
    'उत्तर',         // उ + त + ् + त + र
    'कृष्ण',         // क + ृ + ष + ् + ण
    'दृष्टी',        // द + ृ + ष + ् + ट + ी
    'दृष्टिकोन',     // द + ृ + ष + ् + ट + ि + क + ो + न
    'लक्ष्मी',       // ल + क + ् + ष + ् + म + ी
    'ज्ञानेश्वर',     // ज + ् + ञ + ा + न + े + श + ् + व + र
    'त्र्यंबक',      // त + ् + र + ् + य + ं + ब + क
    'हृदय',          // ह + ृ + द + य
    'श्रेय',         // श + ् + र + े + य
    'श्रेणी',        // श + ् + र + े + ण + ी
    'श्रमिक',        // श + ् + र + म + ि + क (wait no: श + ् + र + ा + म + ि + क)
    'गृह',           // ग + ृ + ह
    'ग्रहण',         // ग + ् + र + ह + ण
    'प्रगती',        // प + ् + र + ग + त + ी
    'द्रव्य',        // द + ् + र + व + ् + य
    'द्राक्ष',       // द + ् + र + ा + क + ् + ष
    'द्वार',         // द + ् + व + ा + र
    'द्वंद्व',       // द + ् + व + ं + द + ् + व
    'ब्रह्म',        // ब + ् + र + ह + ् + म
    'ब्रह्मांड',     // ब + ् + र + ह + ् + म + ा + ं + ड
    'क्रम',          // क + ् + र + म
    'उद्घाटन',      // उ + द + ् + घ + ा + ट + न
    'संध्याकाळ',     // स + ं + ध + ् + य + ा + क + ा + ळ
    'संघटना',       // स + ं + घ + ट + न + ा
    'श्रमिक',       // शश + ् + र + म + ि + क  -> actually श + ् + र + (chhoti i rearranged) म + ि + क
    'शेतकऱ्यांना',  // Farmer
    'स्वच्छता',     // स + ् + व + च + ् + छ + त + ा
    'व्यक्तीचे',    // व + ् + य + क + ् + त + ी + च + े
    'ग्रामीण',       // ग + ् + र + ा + म + ी + ण
    'ग्रंथालयाचा',   // ग + ् + र + ं + थ + ा + ल + य + ा + च + ा
    'प्रामाणिकपणा',  // प + ् + र + ा + म + ा + ण + ि + क + प + ण + ा
    'ऐतिहासिक',      // ऐ + त + ि + ह + ा + स + ि + क
    'किल्ले',        // क + ि + ल + ् + ल + े
];

for (const word of words) {
    const codepoints = [];
    for (const ch of word) {
        codepoints.push(`U+${ch.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')} (${ch})`);
    }
    console.log(`${word}: ${codepoints.join(' + ')}`);
}
